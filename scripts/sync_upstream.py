#!/usr/bin/env python3
"""Import published, versioned upstream app sources; never execute imported code."""
import ast
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / 'sources.lock.json'
APPS = {
    'powerline2mqtt': ('ChristophKomenda/powerline2mqtt', 'haos', 'v', True),
    'pironman-ir-receiver': ('ChristophKomenda/home-assistant-addon', 'pironman-ir-receiver', 'pironman-ir-v', False),
}
VERSION = re.compile(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(alpha|beta|rc)\.(0|[1-9]\d*))?\Z')

def version_key(value):
    m = VERSION.fullmatch(value)
    if not m:
        raise ValueError(f'Unsupported version: {value}')
    a,b,c,stage,n = m.groups()
    return (int(a), int(b), int(c), {'alpha':0,'beta':1,'rc':2,None:3}[stage], int(n or 0))

def select(releases, prefix, current, allow_pre):
    candidates = []
    for r in releases:
        tag = r.get('tag_name', '')
        if r.get('draft') or not tag.startswith(prefix):
            continue
        v = tag[len(prefix):]
        if not VERSION.fullmatch(v):
            continue
        pre = '-' in v
        if bool(r.get('prerelease')) != pre:
            continue
        if pre and (not allow_pre or '-' not in current):
            continue
        if version_key(v) > version_key(current):
            candidates.append((version_key(v), tag, v))
    return max(candidates, default=None)

def run(*args, cwd=None):
    return subprocess.check_output(args, cwd=cwd)

def digest(folder):
    h = hashlib.sha256()
    for p in sorted(folder.rglob('*')):
        if p.is_symlink():
            raise ValueError(f'Symlink not allowed: {p}')
        if p.is_file():
            name = p.relative_to(folder).as_posix().encode()
            h.update(len(name).to_bytes(8,'big') + name + hashlib.sha256(p.read_bytes()).digest())
        elif not p.is_dir():
            raise ValueError(f'Unsupported file: {p}')
    return h.hexdigest()

def validate_app(folder, slug, version):
    cfg = yaml.safe_load((folder / 'config.yaml').read_text())
    if cfg['slug'] != slug or str(cfg['version']) != version:
        raise ValueError(f'{slug}: slug/version mismatch')
    if not cfg.get('arch') or not (folder/'Dockerfile').is_file() or not (folder/'LICENSE').is_file():
        raise ValueError(f'{slug}: missing architecture, Dockerfile or LICENSE')
    for p in folder.rglob('*.yaml'):
        yaml.safe_load(p.read_text())
    for p in folder.rglob('*.json'):
        json.loads(p.read_text())
    for p in folder.rglob('*.py'):
        ast.parse(p.read_text(), filename=str(p))
    return digest(folder)

def validate(lock):
    repo = yaml.safe_load((ROOT/'repository.yaml').read_text())
    if not all(repo.get(k) for k in ('name','url','maintainer')):
        raise ValueError('Invalid repository.yaml')
    if set(lock) != set(APPS):
        raise ValueError('Unexpected lock entries')
    for slug, (repo, directory, prefix, _) in APPS.items():
        entry = lock[slug]
        version_key(entry['version'])
        if (entry['repository'], entry['directory'], entry['tag']) != (repo, directory, prefix+entry['version']):
            raise ValueError(f'{slug}: invalid provenance')
        if not re.fullmatch(r'[0-9a-f]{40}', entry['commit']):
            raise ValueError(f'{slug}: invalid commit')
        if validate_app(ROOT/slug, slug, entry['version']) != entry['sha256']:
            raise ValueError(f'{slug}: content differs from lock; change upstream instead')
    print('Validated both app packages, provenance and content hashes.')

def import_release(repo, directory, tag, dest, temp):
    gitdir = temp/'git'
    run('git','init','--bare',str(gitdir))
    run('git','fetch','--depth=1','--no-tags',f'https://github.com/{repo}.git',f'refs/tags/{tag}',cwd=gitdir)
    commit = run('git','rev-parse','FETCH_HEAD^{commit}',cwd=gitdir).decode().strip()
    archive = temp/'app.tar'
    archive.write_bytes(run('git','archive',f'{commit}:{directory}',cwd=gitdir))
    dest.mkdir()
    with tarfile.open(archive) as tf:
        for member in tf.getmembers():
            if not (member.isfile() or member.isdir()):
                raise ValueError('Unsupported archive entry')
        tf.extractall(dest,filter='data')
    if directory == 'haos':
        # Source package license lives at upstream repository root.
        (dest/'LICENSE').write_bytes(run('git','show',f'{commit}:LICENSE',cwd=gitdir))
    return commit

def write_metadata(lock):
    LOCK.write_text(json.dumps(lock, indent=2, sort_keys=True)+'\n')
    lines = ['# Pinned upstream sources','','Generated by `scripts/sync_upstream.py`.','','| App | Release | Commit | Source directory |','| --- | --- | --- | --- |']
    for slug, e in lock.items():
        base = 'https://github.com/'+e['repository']
        lines.append(f"| {slug} | [{e['tag']}]({base}/releases/tag/{e['tag']}) | [`{e['commit'][:12]}`]({base}/commit/{e['commit']}) | `{e['directory']}` |")
    lines += ['', 'Review upstream changes, permissions and license obligations before merging.']
    (ROOT/'SOURCES.md').write_text('\n'.join(lines)+'\n')

def main():
    lock = json.loads(LOCK.read_text())
    validate(lock)
    if sys.argv[1:] == ['--check']:
        return
    if sys.argv[1:]:
        raise SystemExit('Usage: sync_upstream.py [--check]')
    with tempfile.TemporaryDirectory() as td:
        base = Path(td)
        staged = []
        for slug, (repo, directory, prefix, allow_pre) in APPS.items():
            pages = json.loads(run('gh','api','--paginate','--slurp',f'repos/{repo}/releases?per_page=100'))
            candidate = select([r for page in pages for r in page], prefix, lock[slug]['version'], allow_pre)
            if not candidate:
                print(f'{slug}: no newer eligible release')
                continue
            _, tag, version = candidate
            temp = base/slug
            temp.mkdir()
            dest = temp/'app'
            commit = import_release(repo,directory,tag,dest,temp)
            sha = validate_app(dest,slug,version)
            entry = dict(repository=repo,directory=directory,tag=tag,version=version,commit=commit,sha256=sha)
            staged.append((slug,dest,entry))
        # No tracked changes before all selected packages have passed checks.
        for slug,dest,entry in staged:
            shutil.rmtree(ROOT/slug)
            shutil.copytree(dest,ROOT/slug)
            lock[slug] = entry
            print(f"Imported {slug} {entry['version']} at {entry['commit']}")
        if staged:
            write_metadata(lock)
        validate(lock)

if __name__ == '__main__':
    main()
